  '          <div class="stat">',
  '            <div class="label">${escapeHtml(label)}</div>',
  '            <div class="value">${escapeHtml(value)}</div>',
  '          </div>',
  '        `).join("");',
  '',
  '        const sourceItems = [];',
  '        for (const entry of resources.configured.packages) {',
  '          sourceItems.push(renderConfiguredSource("Package source", "package", entry.source, {',
  '            updateSupported: entry.updateSupported,',
  '            note: entry.updateSupported ? "Remote package source — update pulls the latest version/ref." : "Local package source — remove detaches it from my-pi.",',
  '          }));',
  '        }',
  '        for (const entry of resources.configured.extensionPaths) {',
  '          sourceItems.push(renderConfiguredSource("Extension path", "extension-path", entry, {',
  '            note: "Local extension path managed by my-pi.",',
  '          }));',
  '        }',
  '        for (const entry of resources.configured.skillPaths) {',
  '          sourceItems.push(renderConfiguredSource("Skill path", "skill-path", entry, {',
  '            note: "Local skill path managed by my-pi.",',
  '          }));',
  '        }',
  '        configuredSources.innerHTML = sourceItems.length',
  '          ? sourceItems.join("")',
  '          : `<p class="muted">No my-pi scoped package/path sources configured yet.</p>`;',
  '',
  '        activeChats.innerHTML = renderTable(',
  '          ["Chat", "Messages", "Queue", "Idle timer", "Resource gen"],',
  '          runtime.chats.map((chat) => [',
  '            code(chat.chatId),',
  '            escapeHtml(chat.messageCount),',
  '            escapeHtml(chat.queuedMessages),',
  '            chat.hasIdleTimer ? badge("armed", "good") : badge("inactive", "warn"),',
  '            escapeHtml(chat.resourceGeneration),',
  '          ])',
  '        );',
  '',
  '        extensionsTable.innerHTML = renderTable(',
  '          ["Path", "Managed", "Tools", "Commands"],',
  '          resources.extensions.map((extension) => [',
  '            `',
  '              <div><strong>${escapeHtml(extension.sourceInfo.source)}</strong></div>',
  '              <div class="small">${code(extension.resolvedPath)}</div>',
  '              <div class="small">scope=${escapeHtml(extension.sourceInfo.scope)} · origin=${escapeHtml(extension.sourceInfo.origin)}</div>',
  '            `,',
  '            extension.managedByMyPi ? badge("my-pi", "good") : badge("shared", "warn"),',
  '            extension.tools.length ? extension.tools.map((tool) => badge(tool)).join("") : `<span class="muted">—</span>`,',
  '            extension.commands.length ? extension.commands.map((command) => badge(command)).join("") : `<span class="muted">—</span>`,',
  '          ])',
  '        );',
  '',
  '        skillsTable.innerHTML = renderTable(',
  '          ["Skill", "Managed", "Path"],',
  '          resources.skills.map((skill) => [',
  '            `',
  '              <div><strong>${escapeHtml(skill.name)}</strong></div>',
  '              <div class="small">${escapeHtml(skill.description)}</div>',
  '              <div class="small">source=${escapeHtml(skill.sourceInfo.source)}</div>',
  '            `,',
  '            [',
  '              skill.managedByMyPi ? badge("my-pi", "good") : badge("shared", "warn"),',
  '              skill.disableModelInvocation ? badge("manual only", "bad") : badge("auto-load", "good"),',
  '            ].join(""),',
  '            `<div class="small">${code(skill.filePath)}</div>`,',
  '          ])',
  '        );',
  '',
  '        cronJobs.innerHTML = renderTable(',
  '          ["Job", "Schedule", "Status", "Work dir"],',
  '          automations.cronJobs.map((job) => [',
  '            `',
  '              <div><strong>${escapeHtml(job.name)}</strong></div>',
  '              <div class="small">${code(job.id)}</div>',
  '              <div class="small">${escapeHtml(job.task)}</div>',
  '            `,',
  '            code(job.schedule),',
  '            [',
  '              job.enabled ? badge("enabled", "good") : badge("disabled", "warn"),',
  '              job.lastStatus ? badge(job.lastStatus, job.lastStatus === "error" ? "bad" : job.lastStatus === "skipped" ? "warn" : "good") : "",',
  '            ].join(""),',
  '            `<div class="small">${code(job.workDir)}</div>`,',
  '          ])',
  '        );',
  '',
  '        reminders.innerHTML = renderTable(',
  '          ["Reminder", "Chat", "When"],',
  '          automations.reminders.map((reminder) => [',
  '            escapeHtml(reminder.message),',
  '            code(reminder.chatId),',
  '            escapeHtml(new Date(reminder.fireAt).toLocaleString()),',
  '          ])',
  '        );',
  '',
  '        const diagnosticBlocks = [];',
  '        if (resources.extensionErrors.length) {',
  '          diagnosticBlocks.push(`',
  '            <div class="item">',
  '              <div class="item-title">Extension load errors</div>',
  '              <pre>${escapeHtml(resources.extensionErrors.map((entry) => `${entry.path}: ${entry.error}`).join("\\n"))}</pre>',
  '            </div>',
  '          `);',
  '        }',
  '        if (resources.skillDiagnostics.length) {',
  '          diagnosticBlocks.push(`',
  '            <div class="item">',
  '              <div class="item-title">Skill diagnostics</div>',
  '              <pre>${escapeHtml(resources.skillDiagnostics.map((entry) => `${entry.type || "info"}: ${entry.message}${entry.path ? ` (${entry.path})` : ""}`).join("\\n"))}</pre>',
  '            </div>',
  '          `);',
  '        }',
  '        if (resources.promptDiagnostics.length) {',
  '          diagnosticBlocks.push(`',
  '            <div class="item">',
  '              <div class="item-title">Prompt diagnostics</div>',
  '              <pre>${escapeHtml(resources.promptDiagnostics.map((entry) => `${entry.type || "info"}: ${entry.message}${entry.path ? ` (${entry.path})` : ""}`).join("\\n"))}</pre>',
  '            </div>',
  '          `);',
  '        }',
  '        if (resources.settingsErrors.length) {',
  '          diagnosticBlocks.push(`',
  '            <div class="item">',
  '              <div class="item-title">Settings errors</div>',
  '              <pre>${escapeHtml(resources.settingsErrors.join("\\n"))}</pre>',
  '            </div>',
  '          `);',
  '        }',
  '        diagnostics.innerHTML = diagnosticBlocks.length',
  '          ? diagnosticBlocks.join("")',
  '          : `<p class="muted">No current diagnostics.</p>`;',
  '',
  '        appDetails.innerHTML = `',
  '          <div class="list">',
  '            <div class="item">',
  '              <div class="item-title">Service</div>',
  '              <div class="meta">',
  '                <div>Started: ${escapeHtml(new Date(app.startedAt).toLocaleString())}</div>',
  '                <div>PID: ${escapeHtml(app.pid)}</div>',
  '                <div>Node: ${escapeHtml(app.nodeVersion)}</div>',
  '                <div>Channel: ${escapeHtml(app.channelType)}</div>',
  '              </div>',
  '            </div>',
  '            <div class="item">',
  '              <div class="item-title">Paths</div>',
  '              <div class="meta">',
  '                <div>Default work dir: ${code(app.defaultWorkDir)}</div>',
  '                <div>Data dir: ${code(app.dataDir)}</div>',
  '                <div>My-pi agent dir: ${code(app.myPiAgentDir)}</div>',
  '              </div>',
  '            </div>',
  '            <div class="item">',
  '              <div class="item-title">Resource refresh</div>',
  '              <div class="meta">',
  '                <div>Last refreshed: ${escapeHtml(new Date(resources.refreshedAt).toLocaleString())}</div>',
  '                <div>Resource generation: ${escapeHtml(runtime.resourceGeneration)}</div>',
  '              </div>',
  '            </div>',
  '          </div>',
  '        `;',
