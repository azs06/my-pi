  '              ${renderSourceActionButtons(kind, source, options)}',
  '            </div>',
  '          </div>',
  '        `;',
  '      }',
  '',
  '      async function runResourceAction(action, kind, source, button) {',
  '        if (!action || !kind || !source) return;',
  '',
  '        if (action === "remove") {',
  '          const confirmed = window.confirm(`Remove ${kind} source from my-pi?',
